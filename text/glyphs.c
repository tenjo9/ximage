int main(void)
{
    XImage *img = &(XImage){0};
    img->width = 1000;
    img->height = 100;
    img->data = malloc((size_t)(img->width * img->height) * 4);
    if (!img->data)
    {
        fprintf(stderr, "Image memory allocation error\n");
        exit(69);
    }


    xi_fill_bg(img, 0xff424242);
    xi_draw_rect(img, 0, 50, 1000, 2, 0xff0000ff);

    int scale = 2;
    int base = 50;
    int xcursor = 0;
    size_t len = sizeof(minecraftish_font)/sizeof(Glyph);

    for (size_t i = 33; i < len; ++i)
    {
        Glyph *g = &minecraftish_font[i];
        draw_glyph(img, g, xcursor, base-scale*(g->base+g->height), scale, 0xffffffff);
        xcursor += (1 + scale*g->width);
    }

    draw_glyph(img, &minecraftish_font['a'], 995, 0, 1, 0xff0000ff);


    stbi_write_png("ximage.png", img->width, img->height, 4, (void *)img->data, 4*img->width);
    free(img->data);
    return 0;
}
