void draw_glyph(XImage *img, Glyph *glyph, int x0, int y0, int scale, uint32_t color)
{
    for (int i = 0; i < glyph->width; ++i)
    {
        for (int j = 0; j < glyph->height; ++j)
        {
            if (glyph->bytes[j*glyph->width + i])
            {
                int x1 = x0 + (i*scale), y1 = y0 + (j*scale);
                xi_draw_rect(img, x1, y1, scale, scale, color);
            }
        }
    }
}

